-- StudyMore PostgreSQL baseline. Applied once by src/migrations.py.

CREATE TABLE users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            password TEXT NOT NULL,
            email_verified INTEGER NOT NULL DEFAULT 1
        );

CREATE TABLE study_groups (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            creator_user_id INTEGER,
            group_name TEXT NOT NULL,
            course_code TEXT NOT NULL,
            section TEXT,
            description TEXT NOT NULL,
            meeting_type TEXT NOT NULL,
            meeting_date TEXT NOT NULL,
            meeting_time TEXT NOT NULL,
            location TEXT,
            meeting_link TEXT,
            max_members INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'open', study_goal TEXT, is_private INTEGER NOT NULL DEFAULT 0,
            FOREIGN KEY (creator_user_id) REFERENCES users(id)
        );

CREATE TABLE group_memberships (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            group_id INTEGER NOT NULL,
            UNIQUE(user_id, group_id),
            FOREIGN KEY (user_id) REFERENCES users(id),
            FOREIGN KEY (group_id) REFERENCES study_groups(id)
        );

CREATE TABLE study_requests (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            course_code TEXT NOT NULL,
            section TEXT,
            study_goal TEXT NOT NULL,
            meeting_preference TEXT NOT NULL,
            note TEXT,
            status TEXT NOT NULL DEFAULT 'active',
            created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS')),
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE user_availability (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            day_of_week TEXT NOT NULL,
            start_time TEXT NOT NULL,
            end_time TEXT NOT NULL,
            UNIQUE(user_id, day_of_week, start_time, end_time),
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE study_sessions (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id INTEGER NOT NULL,
            created_by_user_id INTEGER NOT NULL,
            title TEXT NOT NULL,
            session_date TEXT NOT NULL,
            start_time TEXT NOT NULL,
            end_time TEXT NOT NULL,
            recurrence TEXT NOT NULL DEFAULT 'none',
            recurrence_end_date TEXT,
            status TEXT NOT NULL DEFAULT 'scheduled',
            created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS')),
            FOREIGN KEY (group_id) REFERENCES study_groups(id),
            FOREIGN KEY (created_by_user_id) REFERENCES users(id)
        );

CREATE TABLE cancelled_session_occurrences (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id INTEGER NOT NULL,
        occurrence_date TEXT NOT NULL,
        UNIQUE(session_id, occurrence_date),
        FOREIGN KEY (session_id) REFERENCES study_sessions(id)
    );

CREATE TABLE edited_session_occurrences (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            session_id INTEGER NOT NULL,
            original_occurrence_date TEXT NOT NULL,
            title TEXT NOT NULL,
            session_date TEXT NOT NULL,
            start_time TEXT NOT NULL,
            end_time TEXT NOT NULL,
            UNIQUE(session_id, original_occurrence_date),
            FOREIGN KEY (session_id) REFERENCES study_sessions(id)
        );

CREATE TABLE email_verifications (
            user_id INTEGER PRIMARY KEY,
            code_hash TEXT NOT NULL,
            expires_at BIGINT NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            last_sent_at BIGINT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE password_resets (
            user_id INTEGER PRIMARY KEY,
            code_hash TEXT NOT NULL,
            expires_at BIGINT NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            last_sent_at BIGINT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE group_invitations (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id INTEGER NOT NULL,
            inviter_id INTEGER NOT NULL,
            invitee_id INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'pending',
            created_at TEXT NOT NULL,
            responded_at TEXT,
            FOREIGN KEY (group_id) REFERENCES study_groups(id),
            FOREIGN KEY (inviter_id) REFERENCES users(id),
            FOREIGN KEY (invitee_id) REFERENCES users(id)
        );

CREATE TABLE notifications (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            kind TEXT NOT NULL,
            message TEXT NOT NULL,
            link_url TEXT,
            group_id INTEGER,
            related_id INTEGER,
            is_read INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE discussion_posts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        group_id INTEGER NOT NULL REFERENCES study_groups(id),
        author_id INTEGER NOT NULL REFERENCES users(id),
        content TEXT NOT NULL CHECK(length(trim(content)) BETWEEN 1 AND 5000),
        created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS'))
    );

CREATE TABLE discussion_replies (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        post_id INTEGER NOT NULL REFERENCES discussion_posts(id),
        author_id INTEGER NOT NULL REFERENCES users(id),
        content TEXT NOT NULL CHECK(length(trim(content)) BETWEEN 1 AND 5000),
        created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS'))
    );

CREATE TABLE user_profiles (
            user_id INTEGER PRIMARY KEY,
            bio TEXT,
            major TEXT,
            minor TEXT,
            class_year TEXT,
            grad_term TEXT,
            courses TEXT,
            study_style TEXT,
            meeting_pref TEXT,
            group_size TEXT,
            study_goals TEXT,
            can_help TEXT,
            need_help TEXT,
            interests TEXT,
            avatar_color TEXT DEFAULT 'purple',
            show_in_groups INTEGER DEFAULT 1, avatar_path TEXT,
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE semesters (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            name TEXT NOT NULL,
            term TEXT NOT NULL,
            year INTEGER NOT NULL,
            start_date TEXT NOT NULL,
            end_date TEXT NOT NULL,
            is_active INTEGER NOT NULL DEFAULT 0,
            created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS')),
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE TABLE semester_items (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            semester_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            course_code TEXT,
            title TEXT NOT NULL,
            item_type TEXT NOT NULL,
            due_date TEXT NOT NULL,
            notes TEXT,
            source TEXT NOT NULL DEFAULT 'manual',
            created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago', 'YYYY-MM-DD HH24:MI:SS')),
            FOREIGN KEY (semester_id) REFERENCES semesters(id),
            FOREIGN KEY (user_id) REFERENCES users(id)
        );

CREATE UNIQUE INDEX one_pending_invite_per_student
        ON group_invitations (group_id, invitee_id)
        WHERE status = 'pending'
        ;

CREATE INDEX discussion_posts_group_order ON discussion_posts(group_id, created_at, id);

CREATE INDEX discussion_replies_post_order ON discussion_replies(post_id, created_at, id);

CREATE INDEX notifications_by_user ON notifications (user_id, is_read, created_at);

CREATE UNIQUE INDEX notification_deduplication ON notifications(user_id, kind, related_id) WHERE related_id IS NOT NULL;
